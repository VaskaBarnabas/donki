-- 21. fázis: Universal Commerce Protocol (UCP) – a kereskedői oldal állapota (docs/FAZIS21_TERV.md).
-- Az átjáró (ucp/) írja, a portál „UCP-rendelések” oldala olvassa, és itt rögzíti az emberi jóváhagyást.
-- Meglévő adatbázisra: docker exec -i donki-agens-db-1 psql -U postgres < systems/agens/db/14_ucp.sql

create schema if not exists ucp;

create table if not exists ucp.checkout (
  id            text primary key,
  platform      text not null,                       -- a vásárló ágens profiljának URL-je (UCP-Agent)
  allapot       text not null check (allapot in ('incomplete', 'requires_escalation', 'ready_for_complete', 'complete_in_progress', 'completed', 'canceled')),
  penznem       text not null default 'HUF',
  vevo          jsonb,                               -- a kérés buyer mezője (adat, nem utasítás)
  b2b           jsonb,                               -- a com.example.donki.b2b_buyer bővítmény
  ugyfel        jsonb,                               -- az azonosított vevő: {customerId, name, taxNumber}
  tetelek       jsonb not null,                      -- a kért tételek: [{id, sku, quantity}]
  szallitas     jsonb,                               -- a kérés fulfillment mezője (címzés, választott opció)
  ajanlat       text,                                -- AJ-…
  valasz        jsonb,                               -- az utolsó kiszámolt line_items, totals, messages
  fizetes       jsonb,                               -- a lezáráskor kapott fizetési eszköz (token nélkül)
  rendeles      text,                                -- RND-…
  jovahagyas    text not null default 'nincs' check (jovahagyas in ('nincs', 'var', 'jovahagyva', 'elutasitva', 'vegrehajtva', 'hiba')),
  dontotte      text,
  dontes_ido    timestamptz,
  dontes_oka    text,
  hiba          text,
  webhook_url   text,                                -- a platform rendelés-webhookja (a profiljából)
  utolso_esemeny text,                               -- a legutóbb elküldött rendelésállapot ujjlenyomata
  lejar         timestamptz not null,
  letrejott     timestamptz not null default now(),
  modositva     timestamptz not null default now()
);
create index if not exists checkout_jovahagyas_idx on ucp.checkout (jovahagyas) where jovahagyas in ('var', 'jovahagyva');
create index if not exists checkout_rendeles_idx on ucp.checkout (rendeles) where rendeles is not null;

-- Idempotencia: ugyanaz a kulcs ugyanarra a műveletre ugyanazt a választ kapja; más tartalommal 409.
create table if not exists ucp.idempotencia (
  kulcs      text not null,
  muvelet    text not null,
  keres_hash text not null,
  statusz    integer not null,
  valasz     jsonb not null,
  ido        timestamptz not null default now(),
  primary key (kulcs, muvelet)
);

-- Rendelés-webhookok: aláírva küldjük, újrapróbálással.
create table if not exists ucp.webhook (
  id          bigint generated by default as identity primary key,
  rendeles    text not null,
  url         text not null,
  esemeny     jsonb not null,
  kiserlet    integer not null default 0,
  kovetkezo   timestamptz not null default now(),
  allapot     text not null default 'var' check (allapot in ('var', 'elkuldve', 'sikertelen')),
  utolso_hiba text,
  letrejott   timestamptz not null default now()
);
create index if not exists webhook_var_idx on ucp.webhook (kovetkezo) where allapot = 'var';
