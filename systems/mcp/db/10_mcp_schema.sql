-- MCP réteg: a tool hívások naplója (a tokenomics méréshez) és az írási műveletek idempotenciája.
-- Csak a service role éri el; az MCP szerverek írják.

create schema if not exists mcp;

create table mcp.tool_calls (
  id            bigint generated by default as identity primary key,
  called_at     timestamptz not null default now(),
  server        text not null,
  tool          text not null,
  client_id     text not null,
  role          text not null,
  transport     text not null check (transport in ('http', 'stdio')),
  input_summary jsonb,               -- a bemenet, érzékeny mezők nélkül
  ok            boolean not null,
  error_code    text,
  duration_ms   integer not null,
  response_bytes integer not null default 0
);

create index tool_calls_called_at_idx on mcp.tool_calls (called_at);
create index tool_calls_tool_idx on mcp.tool_calls (server, tool);

create table mcp.idempotency (
  idempotency_key text not null,
  server          text not null,
  tool            text not null,
  client_id       text not null,
  response        jsonb not null,
  created_at      timestamptz not null default now(),
  primary key (server, tool, client_id, idempotency_key)
);

grant usage on schema mcp to service_role;
grant all on all tables in schema mcp to service_role;
grant all on all sequences in schema mcp to service_role;
alter default privileges in schema mcp grant all on tables to service_role;
alter default privileges in schema mcp grant all on sequences to service_role;

alter table mcp.tool_calls enable row level security;
alter table mcp.idempotency enable row level security;
